/**
 * Honours Moodle's block "blockform" contract in the Page Builder add block modal.
 *
 * Blocks whose edit form returns true from display_form_when_adding() are returned by the addable
 * blocks service with a non-null "blockform". For those blocks the block instance must NOT be created
 * by following the bui_addblock link; instead the core dynamic form is displayed and the block is
 * created by the form's process_dynamic_submission() only after a successful submit.
 *
 * @module     local_edwiserpagebuilder/addblockform
 * @copyright  (c) 2026 WisdmLabs (https://wisdmlabs.com/) <support@wisdmlabs.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */

import ModalForm from 'core_form/modalform';
import ModalEvents from 'core/modal_events';
import {getString} from 'core/str';
import {exception as displayException} from 'core/notification';

const SELECTOR = '[data-action="showaddblockform"][data-blockname][data-blockform]';

let registered = false;
let pageHash = '';
// True from the moment a form is requested until it has been closed (cancelled) or submitted.
// Prevents double clicks from opening several forms and therefore creating duplicate instances.
let busy = false;

/**
 * Extract the target region from the link Moodle generated for this card (bui_blockregion).
 *
 * @param {HTMLElement} card
 * @return {String}
 */
const getRegion = (card) => {
    const link = card.querySelector('a[href*="bui_addblock"]');
    if (!link) {
        return '';
    }
    try {
        return new URL(link.href, window.location.href).searchParams.get('bui_blockregion') || '';
    } catch (e) {
        return '';
    }
};

/**
 * Open the dynamic form for the clicked block.
 *
 * @param {HTMLElement} card
 */
const showForm = (card) => {
    if (busy) {
        return;
    }
    busy = true;

    const blockName = card.getAttribute('data-blockname');
    const blockTitle = card.getAttribute('data-blocktitle') || blockName;

    const modalForm = new ModalForm({
        modalConfig: {
            title: getString('addblock', 'core_block', blockTitle),
        },
        args: {
            blockname: blockName,
            pagehash: pageHash,
            blockregion: getRegion(card),
        },
        formClass: card.getAttribute('data-blockform'),
        returnFocus: card,
    });

    modalForm.addEventListener(modalForm.events.LOADED, () => {
        // Cancel, close icon, ESC or backdrop: the form is hidden and nothing has been created.
        modalForm.modal.getRoot().on(ModalEvents.hidden, () => {
            busy = false;
        });
    });

    modalForm.addEventListener(modalForm.events.FORM_SUBMITTED, () => {
        // Keep "busy" set: the page is reloaded so the new block shows up, and nothing else may be submitted.
        window.location.reload();
    });

    modalForm.show().catch((error) => {
        busy = false;
        displayException(error);
    });
};

/**
 * Register the (capturing) click listener once.
 *
 * @param {String} pagehash Hash of the page being edited, as generated by moodle_page::get_edited_page_hash().
 */
export const init = (pagehash = '') => {
    if (pagehash) {
        pageHash = pagehash;
    }
    if (registered) {
        return;
    }
    registered = true;

    // Capturing phase so the card's own bui_addblock links (which create the block immediately) never run.
    document.addEventListener('click', (e) => {
        const card = e.target.closest(SELECTOR);
        if (!card || !pageHash) {
            // No page hash (page not in editing mode): fall back to the legacy link behaviour.
            return;
        }
        e.preventDefault();
        e.stopPropagation();
        showForm(card);
    }, true);
};
